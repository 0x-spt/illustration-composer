// Bundles the compose-intent handler into one ES module at api/compose-intent.js.
//
// Why a bundle: @vercel/node runs functions under native Node ESM. The workspace packages ship
// raw TypeScript with extensionless imports and JSON imports without attributes, which Node
// cannot resolve at runtime. esbuild inlines @ic/core and the catalog JSON.
//
// The SDK and zod stay external: both publish real ESM that Node resolves natively, Vercel
// traces them from node_modules, and inlining the SDK alone would grow the bundle from ~0.1 MB
// to 2 MB. zod must be a single instance shared with the SDK's zod helper, so it is external too.
//
// The output is committed: Vercel detects functions in api/ before the build command runs, so a
// file generated only at build time is never deployed. CI rebuilds it and fails on a diff.
import { build } from 'esbuild';
import { writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { format, resolveConfig } from 'prettier';

const root = resolve(import.meta.dirname, '..');
const outfile = resolve(root, 'api/compose-intent.js');

const result = await build({
  absWorkingDir: root,
  entryPoints: ['server/compose-intent.ts'],
  bundle: true,
  write: false,
  platform: 'node',
  format: 'esm',
  target: 'node20',
  external: ['@anthropic-ai/sdk', 'zod'],
  legalComments: 'none',
  charset: 'utf8',
  logLevel: 'warning',
  banner: {
    js: [
      '// Generated by `npm run build:api` from server/compose-intent.ts. Do not edit.',
      '/* eslint-disable */',
    ].join('\n'),
  },
});

// Prettier keeps the committed file stable and consistent with the repo's formatting checks.
const code = result.outputFiles[0].text;
const options = await resolveConfig(outfile);
await writeFile(outfile, await format(code, { ...options, filepath: outfile }));
console.log('build:api → api/compose-intent.js');
