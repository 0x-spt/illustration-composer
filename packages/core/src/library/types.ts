import type { Hex } from '../color/hex';
import type { SlotName } from '../palette/types';

export const ITEM_IDS = [
  'book',
  'phone',
  'puzzle',
  'coin',
  'headphones',
  'lamp',
  'vase',
  'wallet',
  'folder',
  'pen',
] as const;

export type ItemId = (typeof ITEM_IDS)[number];

export type DetailSize = 'L' | 'S';
export type ItemState = 'main' | 'background';

export interface AssetFile {
  /** Path relative to the `@ic/library` package root, e.g. `assets/L/book.main.svg`. */
  file: string;
  width: number;
  height: number;
  viewBox: string;
  /** Id of the palette the asset is drawn in. */
  sourcePalette: string;
  /** Source hex → slot. */
  colorMap: Record<Hex, SlotName>;
  /** Colours with no slot (ΔE above threshold): never recoloured. */
  pinned: Hex[];
}

/**
 * How an item may share space with others (D13). A `flat` item may lie on a `surface`;
 * anything else that touches is a collision. `standing` items (lamp, vase) carry nothing
 * and lie on nothing.
 */
export type Stacking = 'surface' | 'flat' | 'standing';

export interface ItemDef {
  id: ItemId;
  label: string;
  /** Size of the L-main variant. */
  nominalWidth: number;
  nominalHeight: number;
  stacking: Stacking;
  variants: Record<DetailSize, Record<ItemState, AssetFile>>;
}

/** Coarse silhouette of an asset (D13), generated by `npm run library:masks`. */
export interface AssetMask {
  cols: number;
  rows: number;
  /** Row-major occupancy bits, most significant bit first, base64. */
  bits: string;
  /** sha1 of the SVG the mask was rendered from: a stale mask fails the tests. */
  sha1: string;
}

export interface DecorDef {
  id: string;
  /** Id of the `BackgroundPreset` this element belongs to. */
  preset: string;
  size: DetailSize;
  asset: AssetFile;
  /**
   * Corner of the source frame nearest to the element centre; the element's
   * top-left = corner + (dx, dy), in px of the source frame (dx/dy may be negative).
   */
  anchor: { corner: 'tl' | 'tr' | 'bl' | 'br'; dx: number; dy: number };
}

export interface BackgroundPreset {
  id: string;
  label: string;
  size: DetailSize;
  /** Side of the square source frame, px. */
  frameSize: number;
  decorIds: string[];
}

export interface LibraryManifest {
  version: 1;
  figmaFileKey: string;
  syncedAt: string;
  items: ItemDef[];
  decor: DecorDef[];
  backgrounds: BackgroundPreset[];
}

export type Aspect = 'square' | 'landscape' | 'portrait';

export interface TemplateSlot {
  role: 'hero' | 'support' | 'backdrop';
  /** Centre of the item box as a fraction of the frame. */
  cx: number;
  cy: number;
  z: number;
  /** Degrees. */
  rotation: number;
  /** Item drawn in this slot in the source example (reference and tests only). */
  sourceItem: ItemId;
}

export interface LayoutTemplate {
  id: string;
  aspect: Aspect;
  /**
   * globalScale the example was drawn at: hero bbox width / hero `nominalWidth` (≈ 1).
   * A scene of width W uses `scale × W / frame.width`, whatever items fill the slots.
   */
  scale: number;
  /** Size of the source example frame, px. */
  frame: { width: number; height: number };
  slots: TemplateSlot[];
  sourceFrame: string;
}
